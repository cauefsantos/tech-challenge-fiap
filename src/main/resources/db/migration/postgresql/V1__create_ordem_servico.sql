CREATE TABLE cliente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_pessoa VARCHAR(10) NOT NULL,
  documento VARCHAR(14) NOT NULL,
  nome VARCHAR(255) NOT NULL,
  email VARCHAR(255),
  telefone VARCHAR(40),
  data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT ck_cliente_tipo_pessoa CHECK (tipo_pessoa IN ('FISICA', 'JURIDICA'))
);
CREATE UNIQUE INDEX uk_cliente_documento_ativo ON cliente (documento) WHERE ativo;

CREATE TABLE veiculo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES cliente(id),
  placa VARCHAR(7) NOT NULL,
  marca VARCHAR(120) NOT NULL,
  modelo VARCHAR(120) NOT NULL,
  ano INTEGER NOT NULL CHECK (ano >= 1886),
  data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uk_veiculo_id_cliente UNIQUE (id, cliente_id)
);
CREATE UNIQUE INDEX uk_veiculo_placa_ativo ON veiculo (placa) WHERE ativo;

CREATE TABLE servico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(80) NOT NULL UNIQUE,
  nome VARCHAR(255) NOT NULL,
  descricao TEXT,
  valor_base NUMERIC(15,2) NOT NULL CHECK (valor_base >= 0),
  tempo_estimado_segundos BIGINT NOT NULL CHECK (tempo_estimado_segundos > 0),
  data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE material (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(80) NOT NULL UNIQUE,
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('PECA', 'INSUMO')),
  nome VARCHAR(255) NOT NULL,
  descricao TEXT,
  valor_unitario NUMERIC(15,2) NOT NULL CHECK (valor_unitario >= 0),
  unidade_medida VARCHAR(40) NOT NULL,
  quantidade_estoque NUMERIC(15,3) NOT NULL CHECK (quantidade_estoque >= 0),
  estoque_minimo NUMERIC(15,3) NOT NULL CHECK (estoque_minimo >= 0),
  data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ordem_servico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR(32) NOT NULL UNIQUE,
  cliente_id BIGINT NOT NULL REFERENCES cliente(id),
  veiculo_id BIGINT NOT NULL,
  status VARCHAR(40) NOT NULL,
  orcamento_aprovado BOOLEAN NOT NULL DEFAULT FALSE,
  valor_total NUMERIC(15,2) NOT NULL DEFAULT 0,
  criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
  descricao_problema TEXT,
  diagnostico TEXT,
  data_inicio_execucao TIMESTAMP WITH TIME ZONE,
  data_finalizacao TIMESTAMP WITH TIME ZONE,
  data_entrega TIMESTAMP WITH TIME ZONE,
  observacoes TEXT,
  CONSTRAINT fk_os_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo(id),
  CONSTRAINT fk_os_veiculo_cliente FOREIGN KEY (veiculo_id, cliente_id) REFERENCES veiculo(id, cliente_id)
);

CREATE TABLE item_servico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_servico_id BIGINT NOT NULL REFERENCES ordem_servico(id),
  servico_id BIGINT NOT NULL REFERENCES servico(id),
  descricao TEXT NOT NULL,
  quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade > 0),
  valor_unitario NUMERIC(15,2) NOT NULL CHECK (valor_unitario >= 0),
  subtotal NUMERIC(15,2) NOT NULL CHECK (subtotal >= 0),
  tempo_estimado_segundos BIGINT NOT NULL CHECK (tempo_estimado_segundos > 0)
);

CREATE TABLE item_material (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_servico_id BIGINT NOT NULL REFERENCES ordem_servico(id),
  material_id BIGINT NOT NULL REFERENCES material(id),
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('PECA', 'INSUMO')),
  descricao TEXT NOT NULL,
  quantidade NUMERIC(15,3) NOT NULL CHECK (quantidade > 0),
  valor_unitario NUMERIC(15,2) NOT NULL CHECK (valor_unitario >= 0),
  subtotal NUMERIC(15,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE orcamento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_servico_id BIGINT NOT NULL REFERENCES ordem_servico(id),
  versao INTEGER NOT NULL CHECK (versao > 0),
  valor_servicos NUMERIC(15,2) NOT NULL CHECK (valor_servicos >= 0),
  valor_pecas NUMERIC(15,2) NOT NULL CHECK (valor_pecas >= 0),
  valor_insumos NUMERIC(15,2) NOT NULL CHECK (valor_insumos >= 0),
  valor_total NUMERIC(15,2) NOT NULL CHECK (valor_total >= 0),
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE', 'DISPONIBILIZADO', 'APROVADO', 'REJEITADO', 'CANCELADO')),
  data_geracao TIMESTAMP WITH TIME ZONE NOT NULL,
  data_resposta TIMESTAMP WITH TIME ZONE,
  observacao_resposta TEXT,
  CONSTRAINT uk_orcamento_ordem_versao UNIQUE (ordem_servico_id, versao)
);
CREATE UNIQUE INDEX uk_orcamento_aprovado_por_os ON orcamento (ordem_servico_id) WHERE status = 'APROVADO';

CREATE TABLE historico_status (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_servico_id BIGINT NOT NULL REFERENCES ordem_servico(id),
  status_anterior VARCHAR(40),
  status_novo VARCHAR(40) NOT NULL,
  data_alteracao TIMESTAMP WITH TIME ZONE NOT NULL,
  observacao TEXT
);
CREATE INDEX ix_historico_status_ordem_data ON historico_status (ordem_servico_id, data_alteracao);
