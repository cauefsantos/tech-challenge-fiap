CREATE TABLE usuario (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     username VARCHAR(100) NOT NULL,
     password_hash VARCHAR(100) NOT NULL,
     papel VARCHAR(20) NOT NULL,
     enabled BOOLEAN NOT NULL DEFAULT TRUE,
     cliente_id BIGINT,
     created_at TIMESTAMP WITH TIME ZONE NOT NULL,
     updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
     CONSTRAINT uk_usuario_username UNIQUE (username),
     CONSTRAINT ck_usuario_username_normalizado CHECK (username = LOWER(username)),
     CONSTRAINT ck_usuario_papel CHECK (papel IN ('ADMIN', 'FUNCIONARIO', 'CLIENTE')),
     CONSTRAINT uk_usuario_cliente UNIQUE (cliente_id),
     CONSTRAINT fk_usuario_cliente FOREIGN KEY (cliente_id) REFERENCES cliente(id) ON DELETE RESTRICT,
     CONSTRAINT ck_usuario_vinculo CHECK (
         (papel = 'CLIENTE' AND cliente_id IS NOT NULL) OR
         (papel IN ('ADMIN', 'FUNCIONARIO') AND cliente_id IS NULL)
         )
);
