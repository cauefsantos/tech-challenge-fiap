CREATE TABLE historico_status (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_servico_id BIGINT NOT NULL REFERENCES ordem_servico(id),
  status_anterior VARCHAR(40),
  status_novo VARCHAR(40) NOT NULL,
  data_alteracao TIMESTAMP WITH TIME ZONE NOT NULL,
  observacao TEXT
);
CREATE INDEX ix_historico_status_ordem_data ON historico_status (ordem_servico_id, data_alteracao);
